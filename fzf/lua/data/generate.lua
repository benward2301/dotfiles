#!/usr/bin/env -S nvim -l

local NWD = arg[1]
  or (os.getenv('HOME') .. '/.local/share/nvim/lazy/nvim-web-devicons')

package.path = NWD .. '/lua/?.lua;' .. package.path

local variants = {
  dark = {
    by_filename = require('nvim-web-devicons.default.icons_by_filename'),
    by_extension = require('nvim-web-devicons.default.icons_by_file_extension'),
  },
  light = {
    by_filename = require('nvim-web-devicons.light.icons_by_filename'),
    by_extension = require('nvim-web-devicons.light.icons_by_file_extension'),
  },
}

local DEFAULT_ICON = { icon = '\239\131\182', color = '#6d8086' }
local DIR_ICON = { icon = '\239\132\149', color = nil }

local function emit(indent, name, tbl)
  local keys = {}
  for k in pairs(tbl) do keys[#keys + 1] = k end
  table.sort(keys)
  io.write(indent, name, ' = {\n')
  for _, k in ipairs(keys) do
    local v = tbl[k]
    io.write(string.format('%s  [%q] = { icon = %q, color = %q },\n',
      indent, k, v.icon or '', v.color or DEFAULT_ICON.color))
  end
  io.write(indent, '},\n')
end

io.write('-- Generated by data/generate.lua from nvim-web-devicons. Do not edit by hand.\n')
io.write('-- Mirrors fzf-lua\'s on-screen icons (default/dark + light themes).\n')
io.write('return {\n')
io.write(string.format('  default = { icon = %q, color = %q },\n',
  DEFAULT_ICON.icon, DEFAULT_ICON.color))
io.write(string.format('  dir = { icon = %q, color = %s },\n',
  DIR_ICON.icon, DIR_ICON.color and string.format('%q', DIR_ICON.color) or 'nil'))
for _, variant in ipairs({ 'dark', 'light' }) do
  io.write('  ', variant, ' = {\n')
  emit('    ', 'by_filename', variants[variant].by_filename)
  emit('    ', 'by_extension', variants[variant].by_extension)
  io.write('  },\n')
end
io.write('}\n')
